#!/usr/bin/env sh
# Regenerates database/schema.sql from the migration history.
#
# The migrations are the source of truth for the schema; this file is the shape
# they build, written out in one place so a reviewer can read the current
# database without replaying thirty files in their head. It is generated rather
# than maintained by hand because the hand-maintained version fell nine
# migrations behind and nothing noticed.
#
# It starts a throwaway PostgreSQL of the version production runs, applies every
# migration in order with psql, and dumps the schema with that server's own
# pg_dump, so the output does not depend on the client tools installed locally.
#
#   sh tools/schema-snapshot.sh           rewrite database/schema.sql
#   sh tools/schema-snapshot.sh --check   fail if database/schema.sql is stale
#
# CI runs the check, so a migration committed without its snapshot fails the build.
set -eu

image="${POSTGRES_IMAGE:-postgres:18.4-alpine}"
root="$(cd "$(dirname "$0")/.." && pwd)"
target="$root/database/schema.sql"
name="omniflow-schema-snapshot-$$"

cleanup() { docker rm -f "$name" >/dev/null 2>&1 || true; }
trap cleanup EXIT INT TERM

docker run -d --name "$name" -e POSTGRES_PASSWORD=snapshot -e POSTGRES_DB=omniflow \
  -v "$root/database/migrations:/migrations:ro" "$image" >/dev/null

tries=0
until docker exec "$name" pg_isready -U postgres -d omniflow >/dev/null 2>&1; do
  tries=$((tries + 1))
  [ "$tries" -gt 60 ] && { echo "PostgreSQL did not start" >&2; exit 1; }
  sleep 1
done
# pg_isready answers during the image's init restart; wait for the final server.
sleep 2

for file in $(cd "$root/database/migrations" && ls ./*.sql | sort); do
  docker exec -e PGOPTIONS="-c client_min_messages=warning" "$name" psql -q -v ON_ERROR_STOP=1 -U postgres -d omniflow \
    -f "/migrations/${file#./}" >/dev/null
done

output="$(mktemp)"
{
  echo "-- Generated by tools/schema-snapshot.sh from database/migrations. Do not edit."
  echo "-- The migrations are the source of truth; regenerate this file after adding one."
  echo
  # pg_dump 17.6+ fences its output with \restrict lines carrying a random key,
  # which would make every snapshot differ; they are dropped.
  docker exec "$name" pg_dump -U postgres -d omniflow --schema-only --no-owner \
    --no-privileges | grep -v -e '^\\restrict ' -e '^\\unrestrict ' \
    -e '^-- Dumped from database version' -e '^-- Dumped by pg_dump version'
} >"$output"

if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$target" "$output" >/dev/null; then
    diff -u "$target" "$output" | head -40
    echo "database/schema.sql is stale: run sh tools/schema-snapshot.sh and commit it" >&2
    rm -f "$output"
    exit 1
  fi
  rm -f "$output"
  echo "database/schema.sql matches the migrations"
else
  mv "$output" "$target"
  echo "wrote database/schema.sql"
fi
